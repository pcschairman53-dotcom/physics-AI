export function t(lang: Lang, key: keyof typeof strings.en): string {
  return strings[lang][key];
}

export function getGreeting(lang: Lang): string {
  const hour = new Date().getHours();
  if (hour < 12) return t(lang, 'greetingMorning');
  if (hour < 17) return t(lang, 'greetingAfternoon');
  return t(lang, 'greetingEvening');
}
